const pagesDir = path.join(process.cwd(), 'src/pages');

function replaceInFile(filePath) {
    let content = fs.readFileSync(filePath, 'utf8');
    let changed = false;
    for (const [ru, ua] of Object.entries(translations)) {
        if (content.includes(ru)) {
            // Create global regex but safely escape strings first
            const escapedRu = ru.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
            const regex = new RegExp(escapedRu, 'g');
            content = content.replace(regex, ua);
            changed = true;
        }
    }
    if (changed) {
        fs.writeFileSync(filePath, content, 'utf8');
        console.log(`Updated: ${filePath}`);
    }
}

function processDirectory(dir) {
    const files = fs.readdirSync(dir);
    for (const file of files) {
        const fullPath = path.join(dir, file);
        const stat = fs.statSync(fullPath);
        if (stat.isDirectory()) {
            if (fullPath.includes('-ua') || fullPath.includes('ua')) {
                processDirectory(fullPath);
            } else if (!fullPath.includes('-ru') && !fullPath.includes('ru')) {
                processDirectory(fullPath);
            }
        } else if (file.endsWith('-ua.astro')) {
            replaceInFile(fullPath);
        }
    }
}

