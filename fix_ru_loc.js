const pagesDir = path.join(process.cwd(), 'src/pages');

function replaceInFile(filePath) {
    let content = fs.readFileSync(filePath, 'utf8');
    let changed = false;
    for (const [ua, ru] of Object.entries(translations)) {
        if (content.includes(ua)) {
            const escapedUa = ua.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
            const regex = new RegExp(escapedUa, 'g');
            content = content.replace(regex, ru);
            changed = true;
        }
    }
    if (changed) {
        fs.writeFileSync(filePath, content, 'utf8');
        console.log(`Updated: ${filePath}`);
    }
}

function processDirectory(dir) {
    const files = fs.readdirSync(dir);
    for (const file of files) {
        const fullPath = path.join(dir, file);
        const stat = fs.statSync(fullPath);
        if (stat.isDirectory()) {
            if (fullPath.includes('-ru') || fullPath.includes('ru')) {
                processDirectory(fullPath);
            }
        } else if (file.endsWith('-ru.astro') || file.endsWith('.astro')) {
            // we will only process if it's in a -ru directory or ends with -ru.astro
            if (fullPath.includes('-ru')) {
                replaceInFile(fullPath);
            }
        }
    }
}

processDirectory(pagesDir);
